CREATE INDEX IX_HOA_DON_MaKH_NgayLap
    ON dbo.HOA_DON (MaKH, NgayLap DESC)
    WHERE MaKH IS NOT NULL;
GO

CREATE TABLE dbo.CHI_TIET_HOA_DON (
    MaCTHD BIGINT IDENTITY(1,1) NOT NULL,
    MaHD VARCHAR(15) NOT NULL,
    MaSP VARCHAR(10) NOT NULL,
    MaKM VARCHAR(12) NULL,
    SoLuong INT NOT NULL,
    DonGiaBan DECIMAL(18,2) NOT NULL,
    TienGiam DECIMAL(18,2) NOT NULL CONSTRAINT DF_CHI_TIET_HOA_DON_TienGiam DEFAULT (0),
    ThanhTien AS (CONVERT(DECIMAL(18,2), (SoLuong * DonGiaBan) - TienGiam)) PERSISTED,
    CONSTRAINT PK_CHI_TIET_HOA_DON PRIMARY KEY (MaCTHD),
    CONSTRAINT UQ_CHI_TIET_HOA_DON_MaHD_MaSP UNIQUE (MaHD, MaSP),
    CONSTRAINT FK_CHI_TIET_HOA_DON_HOA_DON FOREIGN KEY (MaHD) REFERENCES dbo.HOA_DON (MaHD),
    CONSTRAINT FK_CHI_TIET_HOA_DON_SAN_PHAM FOREIGN KEY (MaSP) REFERENCES dbo.SAN_PHAM (MaSP),
    CONSTRAINT FK_CHI_TIET_HOA_DON_KHUYEN_MAI FOREIGN KEY (MaKM) REFERENCES dbo.KHUYEN_MAI (MaKM),
    CONSTRAINT CK_CHI_TIET_HOA_DON_SoLuong CHECK (SoLuong > 0),
    CONSTRAINT CK_CHI_TIET_HOA_DON_DonGiaBan CHECK (DonGiaBan > 0),
    CONSTRAINT CK_CHI_TIET_HOA_DON_TienGiam CHECK (TienGiam >= 0 AND TienGiam <= SoLuong * DonGiaBan)
);
GO

