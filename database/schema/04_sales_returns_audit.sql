CREATE TABLE dbo.HOA_DON (
    MaHD VARCHAR(15) NOT NULL,
    NgayLap DATETIME2(0) NOT NULL CONSTRAINT DF_HOA_DON_NgayLap DEFAULT (SYSDATETIME()),
    MaCa BIGINT NOT NULL,
    MaKH VARCHAR(10) NULL,
    TongTienHang DECIMAL(18,2) NOT NULL CONSTRAINT DF_HOA_DON_TongTienHang DEFAULT (0),
    TongGiamGia DECIMAL(18,2) NOT NULL CONSTRAINT DF_HOA_DON_TongGiamGia DEFAULT (0),
    TongThanhToan DECIMAL(18,2) NOT NULL CONSTRAINT DF_HOA_DON_TongThanhToan DEFAULT (0),
    DiemSuDung INT NOT NULL CONSTRAINT DF_HOA_DON_DiemSuDung DEFAULT (0),
    DiemTichLuy INT NOT NULL CONSTRAINT DF_HOA_DON_DiemTichLuy DEFAULT (0),
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_HOA_DON_TrangThai DEFAULT ('DRAFT'),
    GhiChu NVARCHAR(255) NULL,
    CONSTRAINT PK_HOA_DON PRIMARY KEY (MaHD),
    CONSTRAINT FK_HOA_DON_CA_LAM_VIEC FOREIGN KEY (MaCa) REFERENCES dbo.CA_LAM_VIEC (MaCa),
    CONSTRAINT FK_HOA_DON_KHACH_HANG FOREIGN KEY (MaKH) REFERENCES dbo.KHACH_HANG (MaKH),
    CONSTRAINT CK_HOA_DON_TongTienHang CHECK (TongTienHang >= 0),
    CONSTRAINT CK_HOA_DON_TongGiamGia CHECK (TongGiamGia >= 0),
    CONSTRAINT CK_HOA_DON_TongThanhToan CHECK (TongThanhToan >= 0),
    CONSTRAINT CK_HOA_DON_DiemSuDung CHECK (DiemSuDung >= 0),
    CONSTRAINT CK_HOA_DON_DiemTichLuy CHECK (DiemTichLuy >= 0),
    CONSTRAINT CK_HOA_DON_TrangThai CHECK (TrangThai IN ('DRAFT', 'PAID', 'CANCELLED', 'REFUNDED'))
