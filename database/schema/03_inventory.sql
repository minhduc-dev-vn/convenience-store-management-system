CREATE TABLE dbo.CA_LAM_VIEC (
    MaCa BIGINT IDENTITY(1,1) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    GioBatDau DATETIME2(0) NOT NULL CONSTRAINT DF_CA_LAM_VIEC_GioBatDau DEFAULT (SYSDATETIME()),
    GioKetThuc DATETIME2(0) NULL,
    TienDauCa DECIMAL(18,2) NOT NULL CONSTRAINT DF_CA_LAM_VIEC_TienDauCa DEFAULT (0),
    TienCuoiCa DECIMAL(18,2) NULL,
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_CA_LAM_VIEC_TrangThai DEFAULT ('OPEN'),
    GhiChu NVARCHAR(255) NULL,
    CONSTRAINT PK_CA_LAM_VIEC PRIMARY KEY (MaCa),
    CONSTRAINT FK_CA_LAM_VIEC_NHAN_VIEN FOREIGN KEY (MaNV) REFERENCES dbo.NHAN_VIEN (MaNV),
    CONSTRAINT CK_CA_LAM_VIEC_GioKetThuc CHECK (GioKetThuc IS NULL OR GioKetThuc >= GioBatDau),
    CONSTRAINT CK_CA_LAM_VIEC_TienDauCa CHECK (TienDauCa >= 0),
    CONSTRAINT CK_CA_LAM_VIEC_TienCuoiCa CHECK (TienCuoiCa IS NULL OR TienCuoiCa >= 0),
    CONSTRAINT CK_CA_LAM_VIEC_TrangThai CHECK (TrangThai IN ('OPEN', 'CLOSED'))
);
GO

CREATE INDEX IX_CA_LAM_VIEC_MaNV_TrangThai
    ON dbo.CA_LAM_VIEC (MaNV, TrangThai);
GO

