CREATE TABLE dbo.LO_HANG (
    MaLo VARCHAR(20) NOT NULL,
    MaSP VARCHAR(10) NOT NULL,
    SoLo VARCHAR(50) NOT NULL,
    NgaySanXuat DATE NULL,
    HanSuDung DATE NULL,
    GiaNhap DECIMAL(18,2) NOT NULL,
    SoLuongTon INT NOT NULL CONSTRAINT DF_LO_HANG_SoLuongTon DEFAULT (0),
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_LO_HANG_TrangThai DEFAULT ('ACTIVE'),
    CONSTRAINT PK_LO_HANG PRIMARY KEY (MaLo),
    CONSTRAINT UQ_LO_HANG_MaSP_SoLo UNIQUE (MaSP, SoLo),
    CONSTRAINT FK_LO_HANG_SAN_PHAM FOREIGN KEY (MaSP) REFERENCES dbo.SAN_PHAM (MaSP),
    CONSTRAINT CK_LO_HANG_HanSuDung CHECK (HanSuDung IS NULL OR NgaySanXuat IS NULL OR HanSuDung > NgaySanXuat),
    CONSTRAINT CK_LO_HANG_GiaNhap CHECK (GiaNhap >= 0),
    CONSTRAINT CK_LO_HANG_SoLuongTon CHECK (SoLuongTon >= 0),
    CONSTRAINT CK_LO_HANG_TrangThai CHECK (TrangThai IN ('ACTIVE', 'BLOCKED', 'EXPIRED'))
);
GO

CREATE INDEX IX_LO_HANG_FEFO
    ON dbo.LO_HANG (MaSP, TrangThai, HanSuDung)
    INCLUDE (SoLuongTon, GiaNhap, SoLo);
GO

CREATE TABLE dbo.CHI_TIET_PHIEU_NHAP (
    MaCTPN BIGINT IDENTITY(1,1) NOT NULL,
    MaPN VARCHAR(15) NOT NULL,
    MaLo VARCHAR(20) NOT NULL,
    SoLuong INT NOT NULL,
    DonGiaNhap DECIMAL(18,2) NOT NULL,
    ThanhTien AS (CONVERT(DECIMAL(18,2), SoLuong * DonGiaNhap)) PERSISTED,
    CONSTRAINT PK_CHI_TIET_PHIEU_NHAP PRIMARY KEY (MaCTPN),
    CONSTRAINT UQ_CHI_TIET_PHIEU_NHAP_MaPN_MaLo UNIQUE (MaPN, MaLo),
    CONSTRAINT FK_CHI_TIET_PHIEU_NHAP_PHIEU_NHAP FOREIGN KEY (MaPN) REFERENCES dbo.PHIEU_NHAP (MaPN),
    CONSTRAINT FK_CHI_TIET_PHIEU_NHAP_LO_HANG FOREIGN KEY (MaLo) REFERENCES dbo.LO_HANG (MaLo),
    CONSTRAINT CK_CHI_TIET_PHIEU_NHAP_SoLuong CHECK (SoLuong > 0),
    CONSTRAINT CK_CHI_TIET_PHIEU_NHAP_DonGiaNhap CHECK (DonGiaNhap >= 0)
);
GO

